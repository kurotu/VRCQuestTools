using System;
using KRT.VRCQuestTools.Utils;
using UnityEngine;

namespace KRT.VRCQuestTools.Models
{
    /// <summary>
    /// Source material which has emission.
    /// </summary>
    internal interface IEmissionSource
    {
        /// <summary>
        /// Gets a value indicating whether the source renders emission.
        /// </summary>
        bool UseEmission { get; }

        /// <summary>
        /// Gets a value indicating whether the emission varies over the surface and needs <see cref="GenerateEmissionMap"/>.
        /// When false, <see cref="EmissionColor"/> and <see cref="EmissionStrength"/> represent the emission.
        /// </summary>
        bool UseEmissionMap { get; }

        /// <summary>
        /// Gets the emission color as a material color (sRGB, may be HDR). It is meaningful when <see cref="UseEmissionMap"/> is false.
        /// </summary>
        Color EmissionColor { get; }

        /// <summary>
        /// Gets the emission strength multiplied to <see cref="EmissionColor"/> in linear space.
        /// </summary>
        float EmissionStrength { get; }

        /// <summary>
        /// Gets the coordinate of the texture generated by <see cref="GenerateEmissionMap"/>.
        /// </summary>
        TextureUV EmissionMapUV { get; }

        /// <summary>
        /// Bakes the emission map.
        /// </summary>
        /// <param name="albedo">Request of the albedo which the emission uses (e.g. emission tinted by the main color).</param>
        /// <param name="maxTextureSize">Max texture size used when the sources have no platform override.</param>
        /// <param name="completion">Completion callback.</param>
        /// <returns>Async callback request.</returns>
        AsyncCallbackRequest GenerateEmissionMap(AlbedoBakeRequest albedo, TextureSizeLimit maxTextureSize, Action<Texture2D> completion);

        /// <summary>
        /// Gets the platform override settings of the emission textures.
        /// </summary>
        /// <returns>Platform override settings, or null if none.</returns>
        (int MaxTextureSize, TextureFormat Format)? GetEmissionMapPlatformOverride();
    }
}
